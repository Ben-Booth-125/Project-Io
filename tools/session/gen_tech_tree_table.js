#!/usr/bin/env node
// gen_tech_tree_table.js — render an age's tech-tree store into the C++ table the sim reads.
//
//   node tools/session/gen_tech_tree_table.js [--check]
//
// Reads docs/economy/tech/digitisation_tree.json (canonical for every node; RESEARCH.md owns the
// grammar, DIGITISATION_TREE.md the prose) and writes src/world/digitisation_tree_data.hpp:
// namespace io::dg, one `node` per store node IN STORE ORDER (the index is the node's identity in
// the sim and on the save seam — reordering the store re-points every saved held set, so the
// store is append-only once a save carries it). Requirement groups become index lists (AND over
// groups, any member satisfies a group), `excludes` an index or -1.
//
// Deterministic: the output is a pure function of the store bytes — no timestamp, no host path.
// --check writes nothing and exits 1 when the checked-in header is stale. Run it beside
// tools/session/tech_tree_store.js (which renders the doc tables from the same store).
'use strict';
const fs = require('fs');
const path = require('path');

const checkOnly = process.argv.slice(2).includes('--check');
const root = path.resolve(__dirname, '..', '..');
const storePath = path.join(root, 'docs', 'economy', 'tech', 'digitisation_tree.json');
const outPath = path.join(root, 'src', 'world', 'digitisation_tree_data.hpp');

const store = JSON.parse(fs.readFileSync(storePath, 'utf8'));
const nodes = store.nodes;
const index = new Map(nodes.map((n, i) => [n.id, i]));
if (index.size !== nodes.length) { console.error('duplicate node ids in the store'); process.exit(1); }

const TIER = { travel: 'travel', minor: 'minor', major: 'major', quest: 'quest' };
let maxGroups = 1, maxMembers = 1;
for (const n of nodes) {
  if (!TIER[n.tier]) { console.error(`${n.id}: unknown tier ${n.tier}`); process.exit(1); }
  maxGroups = Math.max(maxGroups, n.requires.length);
  for (const g of n.requires) maxMembers = Math.max(maxMembers, g.length);
  for (const g of n.requires) for (const r of g)
    if (!index.has(r)) { console.error(`${n.id}: requires unknown ${r}`); process.exit(1); }
  if (n.excludes && !index.has(n.excludes)) { console.error(`${n.id}: excludes unknown ${n.excludes}`); process.exit(1); }
}

// A C string literal in plain ASCII: every non-ASCII byte of the UTF-8 encoding is written as a
// three-digit octal escape (octal never swallows a following character, unlike \x), so the header
// compiles identically under any source charset and the string holds the store's UTF-8 bytes.
const cstr = s => {
  let o = '"';
  for (const b of Buffer.from(String(s), 'utf8')) {
    if (b === 0x5c) o += '\\\\';
    else if (b === 0x22) o += '\\"';
    else if (b >= 0x20 && b < 0x7f) o += String.fromCharCode(b);
    else o += '\\' + b.toString(8).padStart(3, '0');
  }
  return o + '"';
};
const lines = [];
lines.push('#pragma once');
lines.push('');
lines.push('// GENERATED by tools/session/gen_tech_tree_table.js from docs/economy/tech/digitisation_tree.json.');
lines.push('// DO NOT EDIT - edit the store, re-run the generator (and tools/session/tech_tree_store.js for');
lines.push('// the doc tables). The grammar is docs/economy/RESEARCH.md, section "The shape of an age\'s tree".');
lines.push('//');
lines.push('// A node\'s INDEX in `nodes` is its identity in the sim and on the save seam (a nation\'s held');
lines.push('// set is a bitset over these indices), so the store is append-only once a save carries it.');
lines.push('');
lines.push('#include <array>');
lines.push('#include <cstdint>');
lines.push('#include <string_view>');
lines.push('');
lines.push('namespace io::dg {');
lines.push('');
lines.push('enum class tier : std::uint8_t { travel = 0, minor = 1, major = 2, quest = 3 };');
lines.push('');
lines.push(`inline constexpr int node_count        = ${nodes.length};`);
lines.push(`inline constexpr int max_groups        = ${maxGroups}; ///< Most requirement groups any node has.`);
lines.push(`inline constexpr int max_group_members = ${maxMembers}; ///< Most members any one group has.`);
lines.push('');
lines.push('/// One node of the Digitisation tree. `groups[g][m]` is a node index, -1 past the group\'s end;');
lines.push('/// a node is open when every one of its `group_count` groups has at least one held member.');
lines.push('struct node');
lines.push('{');
lines.push('    const char*  id;          ///< Store id, e.g. "DG-PR-EX-A". The key `condition_subject::research` names.');
lines.push('    const char*  name;');
lines.push('    tier         t;');
lines.push('    std::uint8_t ring;        ///< 1..4, inside out.');
lines.push('    std::uint8_t cost_units;  ///< Tier base x ring; RP cost = cost_units x the RP unit.');
lines.push('    std::uint8_t group_count; ///< Requirement groups in use (0 = a root).');
lines.push('    std::array<std::array<std::int16_t, max_group_members>, max_groups> groups;');
lines.push('    std::int16_t excludes;    ///< The pick-one pair sibling\'s index, or -1.');
lines.push('    bool         is_quest;');
lines.push('    bool         is_placeholder;');
lines.push('    bool         is_root;     ///< No requirements: a branch\'s first travel node.');
lines.push('    bool         is_mastery;');
lines.push('    bool         is_joint;');
lines.push('    const char*  branch;      ///< "PR-EX" etc.; "" for a joint.');
lines.push('    const char*  placeholder; ///< The system a placeholder holds the place of; "" otherwise.');
lines.push('    const char*  deed;        ///< A quest\'s deed prose; "" otherwise.');
lines.push('    const char*  advantage;   ///< The effect, as prose. Machine effects are the effect pass\'s.');
lines.push('};');
lines.push('');
lines.push('inline constexpr std::array<node, node_count> nodes = {{');
nodes.forEach((n, i) => {
  const groups = [];
  for (let g = 0; g < maxGroups; ++g) {
    const members = [];
    for (let m = 0; m < maxMembers; ++m) {
      const id = n.requires[g] && n.requires[g][m];
      members.push(id ? index.get(id) : -1);
    }
    groups.push('{' + members.join(', ') + '}');
  }
  const ex = n.excludes ? index.get(n.excludes) : -1;
  lines.push(`    /* ${String(i).padStart(3)} */ {${cstr(n.id)}, ${cstr(n.name)}, tier::${n.tier}, ${n.ring}, ${n.cost_units}, ` +
    `${n.requires.length}, {{${groups.join(', ')}}}, ${ex}, ${n.tier === 'quest'}, ${!!n.placeholder}, ` +
    `${n.requires.length === 0}, ${!!n.mastery}, ${!!n.joint}, ${cstr(n.branch || '')}, ` +
    `${cstr(n.placeholder || '')}, ${cstr(n.deed || '')}, ${cstr(n.advantage || '')}},`);
});
lines.push('}};');
lines.push('');
lines.push('/// The index of the node with store id @p id, or -1. Linear over 160 nodes: a lookup, not a hot path.');
lines.push('constexpr int find_node(std::string_view id)');
lines.push('{');
lines.push('    for (int i = 0; i < node_count; ++i)');
lines.push('        if (id == nodes[static_cast<std::size_t>(i)].id)');
lines.push('            return i;');
lines.push('    return -1;');
lines.push('}');
lines.push('');
lines.push('} // namespace io::dg');
lines.push('');
const out = lines.join('\n');

const current = fs.existsSync(outPath) ? fs.readFileSync(outPath, 'utf8').replace(/\r\n/g, '\n') : '';
if (checkOnly) {
  if (current !== out) { console.error('digitisation_tree_data.hpp is STALE — run node tools/session/gen_tech_tree_table.js'); process.exit(1); }
  console.log(`digitisation_tree_data.hpp is current (${nodes.length} nodes).`);
  process.exit(0);
}
if (current === out) { console.log(`unchanged: ${path.relative(root, outPath)} (${nodes.length} nodes)`); process.exit(0); }
fs.writeFileSync(outPath, out);
console.log(`wrote ${path.relative(root, outPath)} (${nodes.length} nodes, ${maxGroups} groups x ${maxMembers} members max)`);
