// --- a minimal JSON writer: appends to a std::string ------------------------

void json_str(std::string& o, const std::string& s)
{
    o += '"';
    for (const char c : s)
    {
        switch (c)
        {
            case '"':  o += "\\\""; break;
            case '\\': o += "\\\\"; break;
            case '\n': o += "\\n";  break;
            case '\r': o += "\\r";  break;
            case '\t': o += "\\t";  break;
            default:
                if (static_cast<unsigned char>(c) < 0x20)
                {
                    char buf[8];
                    std::snprintf(buf, sizeof buf, "\\u%04x", static_cast<unsigned>(c));
                    o += buf;
                }
                else
                    o += c;
        }
    }
    o += '"';
}

void json_num(std::string& o, double v)
{
    if (!std::isfinite(v)) { o += "null"; return; }
    char buf[40];
    std::snprintf(buf, sizeof buf, "%.6g", v);
    o += buf;
}

void json_int(std::string& o, long long v) { o += std::to_string(v); }

/// `"key":` with the comma the previous field needs.
void key(std::string& o, const char* k)
{
    if (!o.empty() && o.back() != '{' && o.back() != '[')
        o += ',';
    o += '"';
    o += k;
    o += "\":";
}

void kv_str(std::string& o, const char* k, const std::string& v) { key(o, k); json_str(o, v); }
void kv_num(std::string& o, const char* k, double v)             { key(o, k); json_num(o, v); }
void kv_int(std::string& o, const char* k, long long v)          { key(o, k); json_int(o, v); }
void kv_bool(std::string& o, const char* k, bool v)              { key(o, k); o += v ? "true" : "false"; }

/// A comma between array elements.
void elem(std::string& o)
{
    if (!o.empty() && o.back() != '[')
        o += ',';
}

