void date_fields(std::string& o, const world& w, std::uint64_t day_tick)
{
    const ui::fmt::calendar_date d = ui::fmt::date_from_day(day_tick);
    char buf[24];
    std::snprintf(buf, sizeof buf, "%04d-%02d-%02d", d.year, d.month, d.day);
    kv_int(o, "econ_tick", w.current_econ_tick);
    kv_int(o, "day", static_cast<long long>(day_tick));
    kv_str(o, "date", buf);
    kv_int(o, "year", d.year);
    kv_int(o, "quarter_of_year", d.quarter);
}

std::string entity_name(const world& w, entity_id id)
{
    if (const auto n = w.nations.find(id); n != w.nations.end()) // BL-1407: every actor
        return n->second.name;
    return {};
}

std::vector<entity_id> sorted_nations(const world& w)
{
    std::vector<entity_id> ids;
    ids.reserve(w.nations.size());
    for (const auto& [id, n] : w.nations)
        ids.push_back(id);
    std::sort(ids.begin(), ids.end());
    return ids;
}

/// The hook for a nation's policy fields that live outside the budget weights
/// — its tax tier and its Discontent (BL-1335, taxes). Written into the
/// nation's quarter row, after the budget; empty while no such field exists on
/// the nation, so a log from before them simply lacks the keys and
/// play_vs_ai.js reads them only where present.
void nation_policy_fields(std::string& o, const world& w, entity_id nation)
{
    const auto n = w.nations.find(nation);
    if (n == w.nations.end())
        return;
    kv_int(o, "tax_tier", n->second.tax_tier);
    kv_num(o, "discontent", n->second.discontent);
}

